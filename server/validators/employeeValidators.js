import { z } from "zod";

export const createEmployeeSchema = z.object({
  firstName: z.string().trim().min(1, "First name is required"),
  lastName: z.string().trim().min(1, "Last name is required"),
  email: z.string().trim().email("Valid email address is required"),
  password: z.string().min(6, "Password must be at least 6 characters long"),
  phone: z.string().trim().optional().default(""),
  position: z.string().trim().optional().default("Staff"),
  department: z.string().trim().optional().default("Operations"),
  basicSalary: z.coerce.number().min(0, "Basic salary must be non-negative").optional().default(0),
  allowances: z.coerce.number().min(0, "Allowances must be non-negative").optional().default(0),
  deductions: z.coerce.number().min(0, "Deductions must be non-negative").optional().default(0),
  joinDate: z.string().or(z.date()).optional(),
  role: z.enum(["EMPLOYEE", "ADMIN", "HR"]).optional().default("EMPLOYEE"),
  bio: z.string().optional().default(""),
  highestQualification: z.string().optional().default(""),
  passOutYear: z.string().optional().default(""),
  certification: z.string().optional().default(""),
  certificationValidity: z.string().optional().default(""),
  panNumber: z.string().optional().default(""),
  aadharNumber: z.string().optional().default(""),
  isLocationExempt: z.union([z.boolean(), z.string().transform((v) => v === "true")]).optional().default(false),
});

export const updateEmployeeSchema = z.object({
  firstName: z.string().trim().min(1).optional(),
  lastName: z.string().trim().min(1).optional(),
  email: z.string().trim().email().optional(),
  password: z.string().min(6).optional(),
  phone: z.string().trim().optional(),
  position: z.string().trim().optional(),
  department: z.string().trim().optional(),
  employmentStatus: z.enum(["ACTIVE", "INACTIVE", "ON_LEAVE", "TERMINATED"]).optional(),
  basicSalary: z.coerce.number().min(0).optional(),
  allowances: z.coerce.number().min(0).optional(),
  deductions: z.coerce.number().min(0).optional(),
  role: z.enum(["EMPLOYEE", "ADMIN", "HR"]).optional(),
  bio: z.string().optional(),
  highestQualification: z.string().optional(),
  passOutYear: z.string().optional(),
  certification: z.string().optional(),
  certificationValidity: z.string().optional(),
  panNumber: z.string().optional(),
  aadharNumber: z.string().optional(),
  isLocationExempt: z.union([z.boolean(), z.string().transform((v) => v === "true")]).optional(),
});
